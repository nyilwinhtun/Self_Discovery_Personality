const facetByQuestionId = new Map()
for (const facet of FACETS) {
  for (const questionId of FACET_QUESTION_IDS[facet.id] || []) {
    if (facetByQuestionId.has(questionId)) throw new Error(`Question ${questionId} belongs to more than one facet`)
    facetByQuestionId.set(questionId, facet)
  }
}

function addFacetMetadata(question) {
  const facet = facetByQuestionId.get(question.id)
  if (!facet) throw new Error(`Question ${question.id} has no facet assignment`)
  return { ...question, facetId: facet.id, facet: facet.name }
}

